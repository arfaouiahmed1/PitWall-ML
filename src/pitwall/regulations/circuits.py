def get_circuit_config(circuit_short_name: str) -> CircuitConfig | None:
    """Look up circuit config by short name (case-insensitive)."""
    key = circuit_short_name.lower().strip()
    factory = CIRCUIT_REGISTRY.get(key)
    if factory:
        return factory()
    return None


def get_circuit_config_by_key(circuit_key: str) -> CircuitConfig | None:
    """Look up circuit config by OpenF1 circuit_key."""
    for factory in CIRCUIT_REGISTRY.values():
        cfg = factory()
        if cfg.circuit_key == str(circuit_key):
            return cfg
    return None


def all_circuits() -> list[CircuitConfig]:
    """Return all registered circuit configs."""
    return [f() for f in CIRCUIT_REGISTRY.values()]
