"""Circuit configurations for the 2026 regulation era.

Each circuit defines its track segments (corners, straights) with energy
deployment, regeneration, and overtake characteristics. These feed the
Circuit Energy Difficulty Index, the energy deployment predictor, and the
strategy simulator.

Data is derived from public circuit maps and FIA track characteristics for the
2026 season. Segments are ordered by distance through a lap.
"""

from __future__ import annotations

from pitwall.regulations import CircuitConfig, TrackSegment

# ── Sector helpers ────────────────────────────────────────────────────────


def _sector(pct_start: float, pct_end: float, length_m: float) -> TrackSegment:
    """Helper to create a generic sector segment."""
    return TrackSegment(
        name=f"Sectors {pct_start:.0%}-{pct_end:.0%}",
        seg_type="STRAIGHT" if (pct_end - pct_start) > 0.15 else "CORNER",
        start_pct=pct_start,
        end_pct=pct_end,
        length_m=length_m,
    )


